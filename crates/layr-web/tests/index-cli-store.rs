//! Native adapter oracle against the real CLI recipe. No hand-written model fixtures.
use layr_store::format;
use layr_web::Session;
use serde_json::{json, Value};
use std::{collections::BTreeSet, fs, path::Path};
fn objects(root: &Path, prefix: &str) -> Vec<String> {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
        if !dir.exists() {
            return;
        }
        for e in fs::read_dir(dir).unwrap() {
            let p = e.unwrap().path();
            if p.is_dir() {
                walk(root, &p, out)
            } else {
                out.push(p.strip_prefix(root).unwrap().to_str().unwrap().into())
            }
        }
    }
    let mut out = vec![];
    walk(root, &root.join(prefix), &mut out);
    out.sort();
    out
}
fn records(s: &mut Session, root: &Path) {
    for o in objects(root, "records") {
        s.add_segment("test", &o, &fs::read(root.join(&o)).unwrap())
            .unwrap()
    }
    s.finish_records("test").unwrap()
}
fn query(s: &Session, m: &str, a: Value) -> Value {
    serde_json::from_str(&s.query("test", m, &a.to_string(), 0.).unwrap()).unwrap()
}
fn tree(s: &mut Session, root: &Path, object: &str, loaded: &mut BTreeSet<String>) {
    if loaded.contains(object) {
        return;
    }
    let bytes = fs::read(root.join(object)).unwrap();
    let base: Option<String> =
        serde_json::from_str(&s.tree_base("test", object, &bytes).unwrap()).unwrap();
    if let Some(base) = base {
        tree(s, root, &base, loaded)
    }
    s.install_tree("test", object, &bytes).unwrap();
    loaded.insert(object.into());
}
#[test]
#[ignore = "requires LAYR_WEB_INDEX_FIXTURE and LAYR_WEB_INDEX_PERSON generated by the pinned real CLI"]
fn indexed_first_page_file_history_blame_and_public_match_cli() {
    let fixture = std::path::PathBuf::from(std::env::var("LAYR_WEB_INDEX_FIXTURE").unwrap());
    let person = std::path::PathBuf::from(std::env::var("LAYR_WEB_INDEX_PERSON").unwrap());
    let root = fixture.join("archive");
    let descriptor = fs::read_to_string(root.join("store.json")).unwrap();
    let mut s = Session::new();
    s.unlock_recovery(
        &fs::read_to_string(person.join("recovery.txt")).unwrap(),
        &fs::read_to_string(person.join("person-view.json")).unwrap(),
    )
    .unwrap();
    s.open_store(
        "test",
        &descriptor,
        &fs::read(root.join("slots").join(s.slot_name().unwrap())).unwrap(),
    )
    .unwrap();
    records(&mut s, &root);
    let lines: Value =
        serde_json::from_slice(&fs::read(fixture.join("lines.json")).unwrap()).unwrap();
    // The adapter omits the local machine path, as required by the browser contract.
    let expected = Value::Array(
        lines
            .as_array()
            .unwrap()
            .iter()
            .cloned()
            .map(|mut l| {
                l.as_object_mut().unwrap().remove("path");
                l
            })
            .collect(),
    );
    assert_eq!(query(&s, "lines", json!([])), expected);
    let opens = query(&s, "openChanges", json!([]));
    for o in objects(&root, "index/heads") {
        s.add_heads("test", &o, &fs::read(root.join(&o)).unwrap())
            .unwrap()
    }
    assert!(s.use_heads("test").unwrap());
    assert_eq!(query(&s, "lines", json!([])), expected);
    assert_eq!(query(&s, "openChanges", json!([])), opens);
    records(&mut s, &root);
    assert_eq!(query(&s, "loadStatus", json!([]))["provisional"], false);
    let trees = objects(&root, "states")
        .into_iter()
        .filter(|o| format::parse_tree_name(o).is_some())
        .collect::<Vec<_>>();
    let mut loaded = BTreeSet::new();
    for o in &trees {
        tree(&mut s, &root, o, &mut loaded)
    }
    for o in objects(&root, "index")
        .into_iter()
        .filter(|o| o.starts_with("index/paths/") || o.starts_with("index/graph/"))
    {
        s.add_history_index("test", &o, &fs::read(root.join(&o)).unwrap())
            .unwrap()
    }
    for line in lines
        .as_array()
        .unwrap()
        .iter()
        .filter(|l| l["name"] == "main" || l["name"] == "feature")
    {
        let state = line["head"].as_str().unwrap();
        let name = line["name"].as_str().unwrap();
        let versions: Value =
            serde_json::from_str(&s.history_versions("test", state, "test.txt").unwrap()).unwrap();
        let oracle: Value = serde_json::from_slice(
            &fs::read(fixture.join(format!("history-{name}.json"))).unwrap(),
        )
        .unwrap();
        assert_eq!(versions, oracle);
        for version in versions.as_array().unwrap() {
            let id = version["id"].as_str().unwrap();
            let object = trees
                .iter()
                .find(|o| format::parse_tree_name(o).unwrap().0 == id)
                .unwrap();
            let parts: Vec<String> =
                serde_json::from_str(&s.file_parts("test", object, "test.txt").unwrap()).unwrap();
            for part in parts {
                s.add_part("test", &part, &fs::read(root.join(&part)).unwrap())
                    .unwrap()
            }
        }
        let blame = query(&s, "blame", json!([state, "test.txt"]));
        let expected = fs::read_to_string(fixture.join(format!("blame-{name}.txt"))).unwrap();
        let rows = expected.lines().collect::<Vec<_>>();
        assert_eq!(rows.len(), blame["lines"].as_array().unwrap().len());
        for (actual, expected) in blame["lines"].as_array().unwrap().iter().zip(rows) {
            assert_eq!(
                actual["text"].as_str().unwrap(),
                expected.split_once(") ").unwrap().1
            );
            let id = actual["state"].as_str().unwrap().replace('-', "");
            let display = format!("{}{}{}", &id[20..], &id[12..20], &id[..12]);
            let prefix = if actual["boundary"] == true {
                format!("^{}", &display[..7])
            } else {
                display[..8].into()
            };
            assert_eq!(expected.split_whitespace().next().unwrap(), prefix)
        }
    }
    let mut public = Session::new();
    public
        .open_public_store(
            "test",
            &descriptor,
            &fs::read(root.join("public.json")).unwrap(),
            &fs::read(root.join("slots/public.age")).unwrap(),
        )
        .unwrap();
    records(&mut public, &root);
    assert_eq!(query(&public, "lines", json!([])), expected);
    assert_eq!(query(&public, "openChanges", json!([])), opens);
    assert_eq!(
        query(&public, "loadStatus", json!([]))["provisional"],
        false
    );
}
